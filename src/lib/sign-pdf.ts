import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

type Signature = { name: string; tenantName: string; email: string | null; signedAt: string; ip: string | null };

/** Appends a signature certificate page to a PDF and returns the new bytes. */
export async function stampSignedPdf(
  original: Uint8Array,
  info: { documentId: string; title: string; signatures: Signature[] },
): Promise<Uint8Array> {
  const pdf = await PDFDocument.load(original, { ignoreEncryption: true });
  const page = pdf.addPage([612, 792]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const italic = await pdf.embedFont(StandardFonts.HelveticaOblique);
  const navy = rgb(0.055, 0.09, 0.19);
  const muted = rgb(0.36, 0.39, 0.47);

  let y = 740;
  const line = (text: string, opts: { size?: number; f?: typeof font; color?: typeof navy; x?: number } = {}) => {
    page.drawText(text, { x: opts.x ?? 56, y, size: opts.size ?? 11, font: opts.f ?? font, color: opts.color ?? navy });
    y -= (opts.size ?? 11) + 7;
  };

  line("Electronic signature record", { size: 20, f: bold });
  y -= 4;
  line(info.title, { size: 12, f: bold });
  line(`Document ID ${info.documentId}`, { color: muted, size: 9 });
  line("Signed electronically through TenantSpark. Each signer typed their name and agreed to sign electronically.", { color: muted, size: 9 });
  y -= 10;

  for (const s of info.signatures) {
    page.drawLine({ start: { x: 56, y: y + 6 }, end: { x: 556, y: y + 6 }, thickness: 0.6, color: rgb(0.89, 0.91, 0.94) });
    y -= 14;
    page.drawText(s.name, { x: 56, y, size: 22, font: italic, color: navy });
    y -= 30;
    line(`Signer: ${s.tenantName}${s.email ? ` (${s.email})` : ""}`);
    line(`Signed: ${new Date(s.signedAt).toLocaleString("en-US", { dateStyle: "long", timeStyle: "long", timeZone: "America/New_York" })}`);
    if (s.ip) line(`Network address: ${s.ip}`, { color: muted, size: 9 });
    y -= 8;
  }

  page.drawText("Generated by TenantSpark", { x: 56, y: 48, size: 8, font, color: muted });

  // Small "signed" mark on every original page.
  const pages = pdf.getPages();
  for (let i = 0; i < pages.length - 1; i++) {
    const p = pages[i];
    const { width } = p.getSize();
    p.drawText(`Signed electronically via TenantSpark. Record on last page.`, { x: width - 300, y: 14, size: 7, font, color: muted });
  }

  return pdf.save();
}
